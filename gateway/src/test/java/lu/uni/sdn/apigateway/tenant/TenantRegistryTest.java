package lu.uni.sdn.apigateway.tenant;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.node.ArrayNode;
import com.fasterxml.jackson.databind.node.ObjectNode;
import org.junit.Before;
import org.junit.Test;
import org.onlab.packet.IpAddress;
import org.onlab.packet.MacAddress;
import org.onosproject.net.ConnectPoint;

import java.io.InputStream;
import java.util.function.Consumer;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertNull;
import static org.junit.Assert.assertTrue;
import static org.junit.Assert.fail;

/**
 * Tests for {@link TenantRegistry} against the tenants.json fixture
 * (generated by topology/tenants.py json).
 */
public class TenantRegistryTest {

    private final ObjectMapper mapper = new ObjectMapper();
    private ObjectNode fixture;

    @Before
    public void setUp() throws Exception {
        try (InputStream in = getClass().getResourceAsStream("/tenants.json")) {
            fixture = (ObjectNode) mapper.readTree(in);
        }
    }

    @Test
    public void parsesFixture() {
        TenantRegistry r = TenantRegistry.fromJson(fixture);
        assertEquals(2, r.tenants().size());
        Tenant t1 = r.tenant("t1").get();
        assertEquals("lu.uni.sdn.gw.t1", t1.appName());
        assertEquals(2, t1.getHosts().size());
        assertTrue(t1.ownsEdgePort(ConnectPoint.deviceConnectPoint("of:0000000000000002/1")));
        assertFalse(t1.ownsEdgePort(ConnectPoint.deviceConnectPoint("of:0000000000000002/2")));
        assertTrue(t1.ownsMac(MacAddress.valueOf("00:00:00:00:01:02")));
        assertFalse(t1.ownsMac(MacAddress.valueOf("00:00:00:00:02:01")));
        assertTrue(t1.ownsIp(IpAddress.valueOf("10.0.1.200")));
        assertFalse(t1.ownsIp(IpAddress.valueOf("10.0.2.1")));
        assertTrue(t1.getQuotas().isEmpty());
        assertEquals(4, r.trunkPorts().size());
        assertEquals("gw-svc", r.serviceAccount());
    }

    @Test
    public void rolesAndTenants() {
        TenantRegistry r = TenantRegistry.fromJson(fixture);
        assertEquals(GatewayRole.OPERATOR, r.roleOf("t1-op"));
        assertEquals(GatewayRole.VIEWER, r.roleOf("t1-view"));
        assertEquals(GatewayRole.OPERATOR, r.roleOf("t2-op"));
        assertEquals(GatewayRole.ADMIN, r.roleOf("onos"));
        assertEquals(GatewayRole.SERVICE, r.roleOf("gw-svc"));
        assertEquals(GatewayRole.NONE, r.roleOf("guest"));
        assertEquals(GatewayRole.NONE, r.roleOf(null));
        assertEquals("t1", r.tenantOf("t1-op").get().getId());
        assertEquals("t2", r.tenantOf("t2-view").get().getId());
        assertFalse(r.tenantOf("onos").isPresent());
        assertFalse(r.tenantOf("gw-svc").isPresent());
        assertFalse(r.tenantOf(null).isPresent());
    }

    @Test
    public void emptyRegistryKnowsNobody() {
        TenantRegistry r = TenantRegistry.empty();
        assertEquals(GatewayRole.NONE, r.roleOf("onos"));
        assertEquals(GatewayRole.NONE, r.roleOf("t1-op"));
        assertNull(r.serviceAccount());
    }

    @Test
    public void quotasParsed() {
        TenantRegistry r = TenantRegistry.fromJson(mutate(n ->
                t(n, "t1").putObject("quotas").put("maxFlowsPerTenant", 7)));
        assertEquals(Long.valueOf(7), r.tenant("t1").get().getQuotas().get("maxFlowsPerTenant"));
    }

    // ---- rejections -------------------------------------------------------

    @Test
    public void rejectsUnknownRootField() {
        expectInvalid(n -> n.put("extra", 1), "unknown field \"extra\"");
    }

    @Test
    public void rejectsMissingServiceAccount() {
        expectInvalid(n -> n.remove("serviceAccount"), "missing field \"serviceAccount\"");
    }

    @Test
    public void rejectsBadRole() {
        expectInvalid(n -> ((ObjectNode) t(n, "t1").get("accounts")).put("t1-op", "admin"),
                "accounts.t1-op");
    }

    @Test
    public void rejectsAccountInTwoTenants() {
        expectInvalid(n -> ((ObjectNode) t(n, "t2").get("accounts")).put("t1-op", "viewer"),
                "account t1-op is claimed by tenant t1 and tenant t2");
    }

    @Test
    public void rejectsTenantAccountThatIsAdmin() {
        expectInvalid(n -> ((ObjectNode) t(n, "t1").get("accounts")).put("onos", "viewer"),
                "is also an admin");
    }

    @Test
    public void rejectsSharedEdgePort() {
        expectInvalid(n -> ((ArrayNode) t(n, "t2").get("edgePorts")).add("of:0000000000000002/1"),
                "edge port of:0000000000000002/1 is claimed by tenant t1 and tenant t2");
    }

    @Test
    public void rejectsEdgePortThatIsTrunk() {
        expectInvalid(n -> ((ArrayNode) t(n, "t1").get("edgePorts")).add("of:0000000000000001/1"),
                "is also a trunk port");
    }

    @Test
    public void rejectsOverlappingSubnets() {
        expectInvalid(n -> ((ArrayNode) t(n, "t2").get("subnets")).add("10.0.0.0/16"),
                "overlaps");
    }

    @Test
    public void rejectsHostOutsideSubnet() {
        expectInvalid(n -> ((ObjectNode) t(n, "t1").get("hosts").get(0)).put("ip", "10.0.2.9"),
                "outside the tenant's subnets");
    }

    @Test
    public void rejectsHostNotOnEdgePort() {
        expectInvalid(n -> ((ObjectNode) t(n, "t1").get("hosts").get(0))
                        .put("location", "of:0000000000000002/9"),
                "not one of the tenant's edgePorts");
    }

    @Test
    public void rejectsBadMac() {
        expectInvalid(n -> ((ObjectNode) t(n, "t1").get("hosts").get(0)).put("mac", "zz"),
                "hosts[0].mac");
    }

    @Test
    public void rejectsBadConnectPoint() {
        expectInvalid(n -> ((ArrayNode) n.get("trunkPorts")).add("garbage"), "trunkPorts[4]");
    }

    @Test
    public void rejectsDuplicateMacAcrossTenants() {
        expectInvalid(n -> ((ObjectNode) t(n, "t2").get("hosts").get(0)).put("mac", "00:00:00:00:01:01"),
                "host MAC");
    }

    @Test
    public void rejectsDuplicateHostIpWithinTenant() {
        expectInvalid(n -> ((ObjectNode) t(n, "t1").get("hosts").get(1)).put("ip", "10.0.1.1"),
                "host IP 10.0.1.1 is claimed by tenant t1 and tenant t1");
    }

    @Test
    public void knownDevicesAndTrunks() {
        TenantRegistry r = TenantRegistry.fromJson(fixture);
        assertEquals(3, r.knownDevices().size());
        assertTrue(r.isTrunk(ConnectPoint.deviceConnectPoint("of:0000000000000002/3")));
        assertFalse(r.isTrunk(ConnectPoint.deviceConnectPoint("of:0000000000000002/1")));
    }

    @Test
    public void rejectsBadTenantId() {
        expectInvalid(n -> ((ObjectNode) n.get("tenants")).set("t 3", t(n, "t1").deepCopy()),
                "tenant id must match");
    }

    @Test
    public void rejectsNegativeQuota() {
        expectInvalid(n -> t(n, "t1").putObject("quotas").put("maxFlowsPerTenant", -1),
                "non-negative integer");
    }

    @Test
    public void rejectsNonObjectRoot() {
        try {
            TenantRegistry.fromJson(mapper.createArrayNode());
            fail("expected IllegalArgumentException");
        } catch (IllegalArgumentException e) {
            assertTrue(e.getMessage(), e.getMessage().contains("root must be an object"));
        }
    }

    // ---- helpers ----------------------------------------------------------

    private static ObjectNode t(ObjectNode root, String id) {
        return (ObjectNode) root.get("tenants").get(id);
    }

    private JsonNode mutate(Consumer<ObjectNode> change) {
        ObjectNode copy = fixture.deepCopy();
        change.accept(copy);
        return copy;
    }

    private void expectInvalid(Consumer<ObjectNode> change, String expectedMessagePart) {
        JsonNode bad = mutate(change);
        try {
            TenantRegistry.fromJson(bad);
            fail("expected IllegalArgumentException containing: " + expectedMessagePart);
        } catch (IllegalArgumentException e) {
            assertTrue("message was: " + e.getMessage(), e.getMessage().contains(expectedMessagePart));
        }
    }
}
